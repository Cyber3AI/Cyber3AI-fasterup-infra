#!/bin/bash
# Read-only: verifică dacă un senzor e la standardul canonic NEXTGEN (candidat golden). Nu modifică nimic.
Y=/etc/suricata/suricata.yaml
echo "host=$(hostname)"
dpkg-query -W -f='${Package}=${Version}\n' suricata wazuh-agent
echo "hold: $(apt-mark showhold | tr '\n' ' ')"
echo "runmode: $(grep -E '^runmode:' $Y)"
echo "exception-policy: $(grep -E '^[[:space:]]*exception-policy:' $Y | head -1)"
echo "threshold-file: $(grep -E '^[# ]*threshold-file:' $Y)"
echo "fail-open activ: $(grep -cE '^[[:space:]]+fail-open:[[:space:]]*yes' $Y)"
echo "suppress: $(grep -c '^suppress' /etc/suricata/threshold.config)"
echo "HOME_NET: $(grep -E '^[[:space:]]*HOME_NET:' $Y | head -1)"
echo "app-layer dnp3/modbus/enip: $(grep -A2 -E '^[[:space:]]+(dnp3|modbus|enip):' $Y | grep -E 'enabled' | tr -s ' ' | tr '\n' ' ')"
echo "ExecStart: $(systemctl show suricata -p ExecStart | grep -oE '\-q [0-9]' | tr '\n' ' ')"
echo "FORWARD: $(iptables -S FORWARD | tr '\n' ' | ')"
echo "drop rules: $(grep -c '^drop ' /var/lib/suricata/rules/suricata.rules) | drop.conf: $(grep -vc '^#' /etc/suricata/drop.conf 2>/dev/null)"
echo "reguli locale CYBER3: $(cat /var/lib/suricata/rules/cyber3-local.rules 2>/dev/null | grep -v '^#' | grep -c sid)"
echo "bridge sysctl: $(sysctl -n net.bridge.bridge-nf-call-iptables net.bridge.bridge-nf-filter-vlan-tagged 2>/dev/null | tr '\n' ' ')"
echo "modules-load: $(ls /etc/modules-load.d/ | tr '\n' ' ')"
echo "iptables-restore DefaultDependencies: $(systemctl show cyber3-iptables-restore -p DefaultDependencies 2>/dev/null)"
echo "tmpfiles suricata: $(cat /etc/tmpfiles.d/suricata.conf 2>/dev/null)"
echo "logrotate: $(grep -cE 'su suricata suricata|daily' /etc/logrotate.d/suricata 2>/dev/null)"
echo "/var/log/cyber3 owner: $(stat -c %U /var/log/cyber3 2>/dev/null)"
echo "l2shield: $(grep -E '^(MODE|PINS)=' /etc/cyber3/l2shield.conf 2>/dev/null | tr '\n' ' ')"
echo "authd.pass: $(test -s /var/ossec/etc/authd.pass && echo prezent) enrollment agent_name: $(grep -oE '<agent_name>[^<]+' /var/ossec/etc/ossec.conf)"
echo "mleo: $(test -x /usr/local/sbin/cyber3-mleo-contain && echo executor) $(systemctl is-enabled cyber3-mleo-expire.timer 2>/dev/null)"
echo "timere: $(systemctl list-unit-files 'cyber3-*' --no-legend | awk '{print $1"="$2}' | tr '\n' ' ')"
echo "suricata-healthcheck: $(systemctl is-enabled suricata-healthcheck.timer 2>/dev/null)  stock suricata-update.timer: $(systemctl is-enabled suricata-update.timer 2>/dev/null)"
echo "unattended-upgrades: $(systemctl is-enabled unattended-upgrades 2>/dev/null)"
echo "failed units: $(systemctl list-units --failed --no-legend | wc -l)"
echo "gai.conf: $(grep -c '^precedence ::ffff:0:0/96 100' /etc/gai.conf)"
echo "timesyncd: $(grep -rh '^NTP=' /etc/systemd/timesyncd.conf.d/ 2>/dev/null)"
